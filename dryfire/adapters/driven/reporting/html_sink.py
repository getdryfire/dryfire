"""HTML report sink (DF-309) — one self-contained file, no CDN, no build step, no JS.

The first visual output, and it lands now for a reason: a single run is a list (terminals
render that well), but a compare run is a matrix of models × cases (terminals render that
badly). The data finally justifies the format.

Hard constraints (SPEC §9, ARCHITECTURE §11):
  - **One self-contained file.** All CSS is inlined; there are no external assets, no
    fonts, no scripts. It opens from `file://` with the network disabled — an air-gapped
    CI artifact is a real use case. Expandable detail uses native `<details>`/`<summary>`,
    so **no JavaScript is needed**.
  - **No server, ever.** This is a file, not `dryfire ui`.
  - **Semantic HTML first, styling second** — it is fully legible with CSS disabled.

On the template: the shell + CSS is a module constant, not a separate packaged file, on
purpose. A self-contained artifact that must survive `uvx dryfire` cannot risk a template
being dropped from the wheel — a failure that would surface only after publish, invisible
to source-tree tests. A `.py` constant always ships.

The failure view is the priority: full trajectory, tool arguments, assertion messages, and
judge reasoning where present — the turn-by-turn detail that would flood a console.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from html import escape

from dryfire.application.scheduler import CaseResult, RunResult
from dryfire.application.usecases.compare import CompareColumn, CompareResult

